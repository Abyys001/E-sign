"""Regenerate src/server/clauses/library/promoter-global.ts from agreement.md (all numbered sections before SIGNATURES)."""
import re, json, os
here=os.path.dirname(os.path.abspath(__file__))
md=open(os.path.join(here,'agreement.md')).read()
first=re.search(r'^# 3\. ', md, flags=re.M).start()
body=md[first:re.search(r'^# \d+\. SIGNATURES', md, flags=re.M).start()]
parts=re.split(r'^# (\d+)\. (.+)$', body, flags=re.M)
secs=[]
for i in range(1,len(parts),3):
    num,title,text=int(parts[i]),parts[i+1].strip(),parts[i+2]
    lines=[('• '+l[2:]) if l.startswith('- ') else l for l in (x.strip().replace('**','') for x in text.split('\n')) if l and l!='---']
    secs.append((num,title,'\n'.join(lines)))
assert [s[0] for s in secs]==list(range(3,3+len(secs)))
platform='''This Promoter & Event Services Agreement ("Agreement") is entered into between:
Bilit.Events / {{organisation_name}}
Company Registration No.: {{bilit_company_number}}
Customer No.: {{bilit_customer_number}}
Zone: {{bilit_zone}}
Registered Office: {{organisation_address}}
Email: {{support_email}}
Website: https://bilit.events
Hereinafter referred to as "Bilit", "Platform", "we", "us" or "our".'''
promoter='''Legal Name: {{organiser_company}}
Trading Name: {{organiser_trading_name}}
Company/Registration No.: {{organiser_registration_number}}
Registered Address: {{organiser_address}}
Country of Registration: {{organiser_country}}
Email: {{organiser_email}}
Telephone: {{organiser_phone}}
Authorised Representative: {{organiser_name}}, {{organiser_title}}
Hereinafter referred to as "Promoter", "Organiser", "you" or "your".
Bilit and the Promoter are individually a "Party" and together the "Parties".
This Agreement is a global agreement: it applies to every Event of the Promoter for which an Event Schedule is agreed, without the need to sign this Agreement again for each Event.'''
allsecs=[(1,'PLATFORM',platform),(2,'PROMOTER / ORGANISER',promoter)]+secs
slug=lambda t: re.sub(r'[^a-z0-9]+','_',t.lower()).strip('_')[:40]
out=['import { clause, type Category } from "../types";','','/**',
' * Bilit.Events Promoter & Event Services Agreement — GLOBAL version (Bilit\'s own text, one clause per section).',
' * GENERATED by scripts/promoter-agreement/gen-global.py from agreement.md — edit the markdown, not this file.',
' * Rendered in this order with the document\'s own numbering (agreement type `ordered`). No per-event Schedules.',' */',
'const c = (key: string, title: string, body: string) => clause(key, title as Category, "core", title.charAt(0) + title.slice(1).toLowerCase(), `Section: ${title}`, body);','',
'export const PROMOTER_GLOBAL = [']
for n,t,b in allsecs: out.append(f'  c("pg.{n:02d}_{slug(t)}", {json.dumps(t)}, {json.dumps(b, ensure_ascii=False)}),')
out.append('];')
open(os.path.join(here,'../../src/server/clauses/library/promoter-global.ts'),'w').write('\n'.join(out)+'\n')
print(len(allsecs),'sections')
